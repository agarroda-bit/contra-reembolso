import { createServer } from 'vite';
import { chromium } from '@playwright/test';
const server = await createServer({ root: process.cwd(), server: { port: 5195 }, logLevel: 'error' });
await server.listen();
const b = await chromium.launch({ channel: 'chromium', args: ['--use-angle=metal', '--enable-gpu'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:5195/index.html?fase=5');
await p.waitForFunction(() => window.__ready === true, null, { timeout: 60000 });
await p.waitForTimeout(1500);
await p.evaluate(() => [...document.querySelectorAll('.cr-bt')].find((b) => b.textContent.includes('Nueva')).click());
await p.waitForTimeout(800);
await p.evaluate(() => [...document.querySelectorAll('.cr-bt')].find((b) => b.textContent.includes('repartir')).click());
await p.waitForTimeout(1500);
await p.evaluate(() => { __cr.mod.economy.cash = 1234; __cr.mod.economy.bank = 5678; __cr.mod.economy.fame = 250; __cr.mod.combat.give('shotgun'); __cr.mod.save.save(); });
await p.reload();
await p.waitForFunction(() => window.__ready === true, null, { timeout: 60000 });
await p.waitForTimeout(1500);
const sub = await p.evaluate(() => document.querySelector('.cr-bt small')?.textContent);
await p.evaluate(() => [...document.querySelectorAll('.cr-bt')].find((b) => b.textContent.includes('Continuar')).click());
await p.waitForTimeout(1500);
const st = await p.evaluate(() => [__cr.mod.economy.cash, __cr.mod.economy.bank, __cr.mod.economy.fame, [...__cr.mod.combat.owned].join(','), __cr.mod.menus.mode, __cr.mod.tutorial.done]);
console.log('BOTÓN CONTINUAR:', sub, '→ ESTADO:', JSON.stringify(st), 'ERRORES:', errs.length ? errs : 'ninguno');
await b.close();
await server.close();
